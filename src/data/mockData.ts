const TAGS = ["新", "热", "沸", "爆", "推荐"];

function formatHot(value: number): string {
  if (value >= 100000000) {
    return `${(value / 100000000).toFixed(2)}亿`;
  }
  if (value >= 10000) {
    return `${(value / 10000).toFixed(1)}万`;
  }
  return `${value}`;
}

function pickRandom<T>(arr: T[], count: number): T[] {
  const pool = [...arr];
  const result: T[] = [];
  for (let i = 0; i < count && pool.length > 0; i++) {
    const idx = Math.floor(Math.random() * pool.length);
    result.push(pool.splice(idx, 1)[0]);
  }
  return result;
}

export function buildDemoList(
  platformId: PlatformId,
  platformName: string,
  count: number = 15
): PlatformHotList {
  const entries = ENTRIES[platformId] ?? [];
  const picked = pickRandom(entries, Math.min(count, entries.length));
  const baseHot = platformId === "weibo" ? 5000000 : 1000000;

  const items: HotSearchItem[] = picked.map((entry, i) => {
    // 热度从高到低模拟
    const hot = Math.max(
      baseHot,
      Math.round((baseHot * (count - i)) / count + Math.random() * baseHot * 0.3)
    );
    return {
      id: `${platformId}-${i + 1}`,
      title: entry.title,
      desc: entry.desc,
      hot,
      hotLabel: formatHot(hot),
      url: buildPlatformSearchUrl(platformId, entry.title),
      index: i + 1,
      tag: i < 3 ? TAGS[Math.floor(Math.random() * TAGS.length)] : undefined,
    };
  });

  return {
    platformId,
    platformName,
    subtitle: "示例数据",
    source: "Demo",
    updatedAt: new Date().toISOString(),
    total: items.length,
    items,
  };
}
